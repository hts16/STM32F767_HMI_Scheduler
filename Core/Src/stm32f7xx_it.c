/* Báo lỗi bằng màu nền LTDC (không cần SDRAM): tắt 2 layer, đổi màu nền */
static void Fault_ShowColor(uint32_t rgb888)
{
  LTDC_Layer1->CR &= ~LTDC_LxCR_LEN;
  LTDC_Layer2->CR &= ~LTDC_LxCR_LEN;
  LTDC->BCCR = rgb888;
  LTDC->SRCR = LTDC_SRCR_IMR;
}
